// Regenerates the command and settings reference pages from package.json,
// so the docs can't drift from what the extension actually contributes.
import { readFileSync, writeFileSync } from "node:fs";

const pkg = JSON.parse(readFileSync("package.json", "utf8"));
const nls = JSON.parse(readFileSync("package.nls.json", "utf8"));
const text = (value) => (typeof value === "string" ? value.replace(/^%(.+)%$/, (_, key) => nls[key] ?? key) : "");
const cell = (value) => String(value).replaceAll("|", "\\|").replaceAll("\n", " ");

const hidden = new Set(
  (pkg.contributes.menus.commandPalette ?? []).filter((entry) => entry.when === "false").map((entry) => entry.command),
);

const commands = pkg.contributes.commands
  .filter((c) => !hidden.has(c.command))
  .map((c) => `| ${cell(`${c.category}: ${text(c.title)}`)} | \`${c.command}\` |`);

writeFileSync(
  "docs/src/content/docs/reference/commands.md",
  [
    "---",
    "title: Commands",
    "description: Every OpenFiles command in the Command Palette.",
    "---",
    "",
    "<!-- Generated by scripts/gen-readme-tables.mjs. Edit package.json instead. -->",
    "",
    "Open the Command Palette (<kbd>Ctrl+Shift+P</kbd> / <kbd>Cmd+Shift+P</kbd>) and type `OpenFiles`.",
    "",
    "| Command | ID |",
    "|---|---|",
    ...commands,
    "",
    "Any command can be bound to a key: open **Preferences: Open Keyboard Shortcuts**, search for the ID, and assign one. A popular choice is `openfiles.reviewNext`.",
    "",
  ].join("\n"),
);

const settings = Object.entries(pkg.contributes.configuration.properties).map(([key, schema]) => {
  const values = schema.enum ? ` (${schema.enum.map((v) => `\`${v}\``).join(", ")})` : "";
  return `| \`${key}\` | \`${cell(JSON.stringify(schema.default))}\` | ${cell(text(schema.markdownDescription ?? schema.description))}${values} |`;
});

writeFileSync(
  "docs/src/content/docs/reference/settings.md",
  [
    "---",
    "title: Settings",
    "description: Every OpenFiles setting with its default.",
    "---",
    "",
    "<!-- Generated by scripts/gen-readme-tables.mjs. Edit package.json instead. -->",
    "",
    "| Setting | Default | Description |",
    "|---|---|---|",
    ...settings,
    "",
  ].join("\n"),
);

console.log(`Wrote ${commands.length} commands and ${settings.length} settings.`);
